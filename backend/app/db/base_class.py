"""Declarative base and reusable model mixins.

Conventions applied across every table:
- UUID primary keys (globally unique, non-enumerable).
- ``created_at`` / ``updated_at`` audit timestamps (UTC, DB-managed).
- Soft delete via ``deleted_at`` (nullable) so records are recoverable and
  auditable rather than physically removed.
- ``TenantMixin`` adds ``tenant_id`` for RLS-scoped tables.
- Naming convention for constraints keeps Alembic migrations deterministic.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column

# Deterministic constraint naming => clean, reviewable autogenerated migrations.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class SoftDeleteMixin:
    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, default=None, index=True
    )

    @property
    def is_deleted(self) -> bool:
        return self.deleted_at is not None


class TenantMixin:
    """Adds a ``tenant_id`` FK. RLS policies (created in migrations) restrict
    visibility to the current tenant. Declared as a mixin so every bounded
    context shares the exact same column definition and index."""

    @declared_attr
    def tenant_id(cls) -> Mapped[uuid.UUID]:  # noqa: N805
        return mapped_column(
            Uuid(as_uuid=True),
            ForeignKey("tenants.id", ondelete="CASCADE"),
            nullable=False,
            index=True,
        )


class AuditedBase(Base, UUIDPrimaryKeyMixin, TimestampMixin, SoftDeleteMixin):
    """Non-tenant global tables (e.g. the tenant registry itself)."""

    __abstract__ = True


class TenantScopedBase(AuditedBase, TenantMixin):
    """Base for all tenant-owned tables — carries tenant_id + audit + soft delete."""

    __abstract__ = True
